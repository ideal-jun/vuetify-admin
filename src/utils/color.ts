export const COLOR_PALETTE_NUMBERS = [
  50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950,
] as const;

export type ColorPaletteNumber = (typeof COLOR_PALETTE_NUMBERS)[number];

export interface RgbColor {
  r: number;
  g: number;
  b: number;
}

interface HslColor {
  h: number;
  s: number;
  l: number;
}

const HEX_SHORT = /^#([\da-f])([\da-f])([\da-f])$/iu;
const HEX_LONG = /^#([\da-f]{2})([\da-f]{2})([\da-f]{2})$/iu;
const RGB_FUNC = /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/iu;

function clamp(value: number, min = 0, max = 255) {
  return Math.min(Math.max(value, min), max);
}

/** Parse a hex or rgb color into rgb channels */
export function getRgb(color: string): RgbColor {
  const value = color.trim();

  const short = value.match(HEX_SHORT);

  if (short) {
    const [, r = '0', g = '0', b = '0'] = short;

    return {
      r: Number.parseInt(r + r, 16),
      g: Number.parseInt(g + g, 16),
      b: Number.parseInt(b + b, 16),
    };
  }

  const long = value.match(HEX_LONG);

  if (long) {
    const [, r = '0', g = '0', b = '0'] = long;

    return {
      r: Number.parseInt(r, 16),
      g: Number.parseInt(g, 16),
      b: Number.parseInt(b, 16),
    };
  }

  const rgb = value.match(RGB_FUNC);

  if (rgb) {
    const [, r = '0', g = '0', b = '0'] = rgb;

    return {
      r: clamp(Number(r)),
      g: clamp(Number(g)),
      b: clamp(Number(b)),
    };
  }

  return { r: 0, g: 0, b: 0 };
}

/** Convert rgb channels to a hex color */
export function getHex({ r, g, b }: RgbColor) {
  return `#${[r, g, b].map((value) => Math.round(value).toString(16).padStart(2, '0')).join('')}`;
}

/** Add an alpha channel to a color */
export function addColorAlpha(color: string, alpha: number) {
  const { r, g, b } = getRgb(color);

  return `rgba(${r}, ${g}, ${b}, ${Math.min(Math.max(alpha, 0), 1)})`;
}

/** Mix a translucent color over a background and return the equivalent opaque hex color */
export function transformColorWithOpacity(color: string, alpha: number, bgColor = '#ffffff') {
  const foreground = getRgb(color);
  const background = getRgb(bgColor);
  const ratio = Math.min(Math.max(alpha, 0), 1);

  return getHex({
    r: background.r + (foreground.r - background.r) * ratio,
    g: background.g + (foreground.g - background.g) * ratio,
    b: background.b + (foreground.b - background.b) * ratio,
  });
}

function rgbToHsl({ r, g, b }: RgbColor): HslColor {
  const rn = r / 255;
  const gn = g / 255;
  const bn = b / 255;

  const max = Math.max(rn, gn, bn);
  const min = Math.min(rn, gn, bn);
  const delta = max - min;

  let h = 0;

  if (delta !== 0) {
    if (max === rn) {
      h = ((gn - bn) / delta) % 6;
    } else if (max === gn) {
      h = (bn - rn) / delta + 2;
    } else {
      h = (rn - gn) / delta + 4;
    }
  }

  h = Math.round(h * 60);

  if (h < 0) {
    h += 360;
  }

  const l = (max + min) / 2;

  const s = delta === 0 ? 0 : delta / (1 - Math.abs(2 * l - 1));

  return { h, s, l };
}

function hslToHex({ h, s, l }: HslColor) {
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;

  let r: number;
  let g: number;
  let b: number;

  if (h >= 0 && h < 60) {
    [r, g, b] = [c, x, 0];
  } else if (h < 120) {
    [r, g, b] = [x, c, 0];
  } else if (h < 180) {
    [r, g, b] = [0, c, x];
  } else if (h < 240) {
    [r, g, b] = [0, x, c];
  } else if (h < 300) {
    [r, g, b] = [x, 0, c];
  } else {
    [r, g, b] = [c, 0, x];
  }

  return getHex({
    r: (r + m) * 255,
    g: (g + m) * 255,
    b: (b + m) * 255,
  });
}

/** The lightness offset from the base color (500) for each palette number */
const PALETTE_LIGHTNESS_OFFSET: Record<ColorPaletteNumber, number> = {
  50: 42,
  100: 34,
  200: 25,
  300: 16,
  400: 8,
  500: 0,
  600: -9,
  700: -17,
  800: -25,
  900: -32,
  950: -38,
};

/**
 * Create a color palette from a color
 *
 * The input color is used as the 500 shade, other shades are generated by varying the lightness while keeping the
 * hue and saturation of the base color.
 */
export function getColorPalette(
  color: string,
  recommended = false,
): Map<ColorPaletteNumber, string> {
  const rgb = getRgb(color);
  const hsl = rgbToHsl(rgb);

  // A recommended color gets a small saturation boost so the palette stays vivid in both themes.
  const saturation = recommended ? Math.min(hsl.s * 1.08, 1) : hsl.s;

  const palette = new Map<ColorPaletteNumber, string>();

  for (const number of COLOR_PALETTE_NUMBERS) {
    const offset = PALETTE_LIGHTNESS_OFFSET[number];

    // Lighter shades are slightly desaturated, which is how most design systems build their ramps.
    const lightnessFactor = 1 - Math.max(offset, 0) / 220;
    const lightness = Math.min(Math.max(hsl.l + offset / 100, 0.04), 0.98);

    palette.set(
      number,
      hslToHex({
        h: hsl.h,
        s: saturation * lightnessFactor,
        l: lightness,
      }),
    );
  }

  // Always keep the exact base color at the 500 shade.
  palette.set(500, getHex(rgb));

  return palette;
}

/** Get a palette color by number */
export function getPaletteColorByNumber(
  color: string,
  number: ColorPaletteNumber = 500,
  recommended = false,
) {
  return getColorPalette(color, recommended).get(number) ?? color;
}

/** Convert a color to a css rgb triplet, e.g. "24 103 192" */
export function getRgbString(color: string) {
  const { r, g, b } = getRgb(color);

  return `${r} ${g} ${b}`;
}

/** Get the contrast color (black or white) for a background color */
export function getContrastColor(color: string) {
  const { r, g, b } = getRgb(color);

  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;

  return luminance > 0.6 ? '#1f1f1f' : '#ffffff';
}
